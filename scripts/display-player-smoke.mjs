import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const migration = read("supabase/migrations/20260831_display_devices.sql");
const targetingMigration = read("supabase/migrations/20260902_campaign_targeting.sql");
const safetyMigration = read("supabase/migrations/20260905_safe_display_delivery.sql");
const records = read("api/dashboard/records.ts");
const player = read("src/player/main.tsx");
const playerHtml = read("player.html");
const playerManifest = JSON.parse(read("public/site/player.webmanifest"));
const portal = read("src/portal/main.tsx");
const displayManagement = read("src/portal/DisplayManagementView.tsx");
const vercel = JSON.parse(read("vercel.json"));

assert.ok(existsSync(new URL("../player.html", import.meta.url)), "Player-Einstieg fehlt");
assert.ok(existsSync(new URL("../dist/player.html", import.meta.url)), "Player fehlt im Produktions-Build");
assert.ok(existsSync(new URL("../dist/player.webmanifest", import.meta.url)), "Player-Manifest fehlt im Produktions-Build");
assert.equal(playerManifest.start_url, "/player", "Player-App startet nicht direkt im Player");
assert.ok([playerManifest.display, ...(playerManifest.display_override || [])].includes("standalone"), "Player-App besitzt keinen Standalone-Modus");
assert.match(playerHtml, /rel="manifest" href="\/player\.webmanifest"/, "Player-Manifest ist nicht eingebunden");
assert.match(playerHtml, /apple-mobile-web-app-capable/, "iOS-Standalone-Modus fehlt");
assert.ok(vercel.rewrites.some((rule) => rule.source === "/player" && rule.destination === "/player.html"), "Player-Rewrite fehlt");
assert.match(migration, /device_token_hash/);
assert.match(migration, /pairing_code_hash/);
assert.match(migration, /configuration_version/);
assert.match(records, /createHash\("sha256"\).*device_token_hash/s, "Gerätetoken wird nicht gehasht gespeichert");
assert.match(records, /mode === "pair"/);
assert.match(records, /mode === "heartbeat"/);
assert.match(records, /action === "renew_display_pairing"[\s\S]*device_token_hash: null[\s\S]*status: "provisioning"/, "Ein neuer Aktivierungscode muss die alte Player-Verbindung beenden");
assert.match(records, /search\.get\("device"\) === "config"/);
assert.match(records, /portalPreview/, "Eine sichere Portal-Player-Vorschau fehlt");
assert.match(records, /\["approved", "published"\]/, "Nicht freigegebene Inhalte dürfen nicht auf Displays erscheinen");
assert.match(records, /Geben Sie alle gewählten Motive vor dem Start frei/);
assert.match(targetingMigration, /tenant_campaign_display_content/, "Zielbezogene Display-Playlists fehlen");
assert.match(records, /targetContentByCampaign/, "Der Player berücksichtigt keine zielbezogenen Playlists");
assert.match(player, /swisscompact_device_token/);
assert.match(player, /device=heartbeat/);
assert.match(player, /device=config/);
assert.doesNotMatch(player, /\[token, config, previewDisplayId\]/, "Konfigurationsänderungen dürfen keine sofortige Abrufschleife auslösen");
assert.match(player, /videoRef\.current/, "Player überwacht die Videowiedergabe nicht");
assert.match(player, /preload="auto"/, "Videos werden nicht frühzeitig geladen");
assert.match(player, /onCanPlay=\{\(\) => void start\(\)\}/, "Video startet nach dem Laden nicht erneut");
assert.match(player, /onError=\{\(\) => \{ setPlayback\("error"\); onFailure\(\); \}\}/, "Videofehler werden nicht behandelt");
assert.match(player, /config\?\.playlist\.length === 1/, "Ein einzelnes Video wird nicht wiederholt");
assert.match(player, /searchParams\.get\("pair"\)|query\.get\("pair"\)/, "Direkter Neuverbindungsmodus fehlt");
assert.match(player, /query\.get\("code"\)/, "Aktivierungscode aus QR-Link wird nicht übernommen");
assert.match(player, /query\.get\("connect"\).*=== "1"/, "QR-Verbindung wird nicht automatisch gestartet");
assert.match(player, /new QrScanner/, "Kamera-QR-Scanner fehlt im Player");
assert.match(player, /preferredCamera: "environment"/, "QR-Scanner verwendet nicht bevorzugt die Rückkamera");
assert.match(player, /parsePairingQr/, "Gescannte QR-Codes werden nicht sicher validiert");
assert.match(player, /QR-Bild auswählen/, "QR-Bild-Fallback fehlt");
assert.match(player, /Aktivierungscode eingeben/, "Manuelle Neuverbindung auf der Leerlaufseite fehlt");
assert.match(portal, /pair=1/, "Portal-Link öffnet den Player nicht im Neuverbindungsmodus");
assert.match(portal.concat(displayManagement), /Player öffnen/, "Direkter Player-Button bei Bildschirmen fehlt");
assert.match(portal, /QRCode\.toDataURL/, "QR-Code für die Bildschirmverbindung fehlt");
assert.match(portal, /1 · Bildschirm-ID[\s\S]*2 · Aktivierungscode/, "Bildschirm-ID und Aktivierungscode sind im Portal nicht logisch geordnet");
assert.match(player, /portalPreview=/, "Player lädt die Portal-Vorschau nicht");
assert.match(portal, /Bildschirm einrichten/);
assert.match(portal.concat(displayManagement), /Aktivierungscode erstellen/);
assert.match(portal, /Code wird erstellt/);
assert.match(portal, /deferredPairings/, "Die Geräteaktivierung wird in der Kampagnenplanung nicht bis zum Abschluss zurückgestellt");
assert.match(portal, /Der QR-Code zur Geräteverbindung erscheint erst nach dem Abschluss der Kampagne/, "Der verschobene Aktivierungsschritt wird nicht verständlich erklärt");
assert.match(portal, /role="alert"/);
assert.match(portal, /Für Bildschirme freigeben/);
assert.match(safetyMigration, /tenant_display_config_versions/, "Versionierte Displaykonfigurationen fehlen");
assert.match(safetyMigration, /tenant_display_test_publications/, "Testveröffentlichungen fehlen");
assert.match(safetyMigration, /tenant_display_alerts/, "Displaywarnungen fehlen");
assert.match(records, /mode === "ack"/, "Der Player bestätigt Auslieferungen nicht");
assert.match(records, /test_publish_campaign/, "Einzelbildschirm-Test fehlt");
assert.match(records, /rollback_display/, "Rollback fehlt");
assert.match(records, /campaignConflicts/, "Kampagnenkonflikte werden nicht geprüft");
assert.match(player, /swisscompact-player-media-v1/, "Offline-Mediencache fehlt");
assert.match(player, /fallback/, "Ersatzinhalt fehlt im Player");
assert.match(player, /PlayerDisplayControls/, "Installations- und Vollbildführung fehlt");
assert.match(player, /Zum Home-Bildschirm/, "iOS-Installationshinweis fehlt");
assert.match(portal, /Sicher veröffentlichen/, "Geführte sichere Veröffentlichung fehlt im Portal");

console.log("Display player smoke checks passed.");
